"""RFC 7807 Problem Details compliant error handling for Agentic-Code-RAG API."""

from __future__ import annotations

from typing import Any

from fastapi import HTTPException, Request, status
from fastapi.exceptions import RequestValidationError
from fastapi.responses import JSONResponse
from pydantic import BaseModel, Field

from src.core.logger import setup_logger

logger = setup_logger("agentic-errors")


class ProblemDetails(BaseModel):
    """RFC 7807 Problem Details schema for machine-readable HTTP error payloads."""

    type: str = Field(
        default="about:blank",
        description="A URI reference that identifies the problem type.",
    )
    title: str = Field(
        ...,
        description="A short, human-readable summary of the problem type.",
    )
    status: int = Field(
        ...,
        description="The HTTP status code generated by the origin server.",
    )
    detail: str = Field(
        ...,
        description="A human-readable explanation specific to this occurrence of the problem.",
    )
    instance: str | None = Field(
        default=None,
        description="A URI reference that identifies the specific occurrence of the problem.",
    )
    invalid_params: list[dict[str, Any]] | None = Field(
        default=None,
        description="Optional list of invalid query/body parameters for validation errors.",
    )


class APIError(HTTPException):
    """Base API exception that translates into RFC 7807 Problem Details."""

    def __init__(
        self,
        status_code: int,
        title: str,
        detail: str,
        error_type: str = "about:blank",
        headers: dict[str, str] | None = None,
    ) -> None:
        super().__init__(status_code=status_code, detail=detail, headers=headers)
        self.title = title
        self.error_type = error_type


class RepoNotFoundError(APIError):
    """Raised when an operation targets an unindexed or nonexistent repository."""

    def __init__(self, repo_id: str) -> None:
        super().__init__(
            status_code=status.HTTP_404_NOT_FOUND,
            title="Repository Not Found",
            detail=f"Repository '{repo_id}' has not been indexed or does not exist.",
            error_type="urn:agentic:error:repo-not-found",
        )


class JobNotFoundError(APIError):
    """Raised when an indexing job ID cannot be located."""

    def __init__(self, job_id: str) -> None:
        super().__init__(
            status_code=status.HTTP_404_NOT_FOUND,
            title="Indexing Job Not Found",
            detail=f"No indexing job found with ID '{job_id}'.",
            error_type="urn:agentic:error:job-not-found",
        )


class PathTraversalError(APIError):
    """Raised when a file path violates security boundary constraints."""

    def __init__(self, path: str) -> None:
        super().__init__(
            status_code=status.HTTP_403_FORBIDDEN,
            title="Access Denied: Path Traversal",
            detail=f"Access to path '{path}' was denied due to directory traversal restrictions.",
            error_type="urn:agentic:error:path-traversal",
        )


async def api_error_handler(request: Request, exc: APIError) -> JSONResponse:
    """Exception handler translating custom APIErrors into RFC 7807 responses."""
    problem = ProblemDetails(
        type=exc.error_type,
        title=exc.title,
        status=exc.status_code,
        detail=exc.detail,
        instance=str(request.url),
    )
    logger.warning(f"Handled API error [{exc.status_code}] on {request.url.path}: {exc.detail}")
    return JSONResponse(
        status_code=exc.status_code,
        content=problem.model_dump(exclude_none=True),
        media_type="application/problem+json",
        headers=exc.headers,
    )


async def validation_error_handler(
    request: Request,
    exc: RequestValidationError,
) -> JSONResponse:
    """Translates FastAPI/Pydantic validation errors into RFC 7807 Problem Details."""
    invalid_params = []
    for err in exc.errors():
        loc = " -> ".join(str(x) for x in err.get("loc", []))
        invalid_params.append(
            {
                "field": loc,
                "reason": err.get("msg", "Invalid parameter"),
                "type": err.get("type", "value_error"),
            }
        )

    problem = ProblemDetails(
        type="urn:agentic:error:validation-error",
        title="Request Validation Failed",
        status=status.HTTP_422_UNPROCESSABLE_ENTITY,
        detail="One or more fields in the request failed validation checks.",
        instance=str(request.url),
        invalid_params=invalid_params,
    )
    logger.info(f"Validation error on {request.url.path}: {invalid_params}")
    return JSONResponse(
        status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,
        content=problem.model_dump(exclude_none=True),
        media_type="application/problem+json",
    )


async def generic_exception_handler(request: Request, exc: Exception) -> JSONResponse:
    """Catch-all handler for unhandled internal server exceptions."""
    logger.error(f"Unhandled server exception on {request.url.path}: {exc}", exc_info=True)
    problem = ProblemDetails(
        type="urn:agentic:error:internal-server-error",
        title="Internal Server Error",
        status=status.HTTP_500_INTERNAL_SERVER_ERROR,
        detail="An unexpected error occurred while processing the request. Check server logs.",
        instance=str(request.url),
    )
    return JSONResponse(
        status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
        content=problem.model_dump(exclude_none=True),
        media_type="application/problem+json",
    )
